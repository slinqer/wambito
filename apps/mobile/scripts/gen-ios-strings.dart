// ignore_for_file: file_names, avoid_print

/// Generates ios/Runner/<language>.lproj/Notices.strings from the Android string resources, so the
/// two notices say the same words on both phones: `values/` is Spanish, `values-en/`, `values-it/`
/// and `values-pt/` the others (android/app/src/main/res).
///
/// Only the words of the notices themselves are taken: [keys]. Android escapes (`\'`, `\"`, `\\`,
/// `\n`, `&amp;`...) are undone and `.strings` ones applied; `%1$s` becomes `%@`.
///
/// Usage, from apps/mobile: dart run scripts/gen-ios-strings.dart
/// CI regenerates the files and fails when the committed ones differ.
library;

import 'dart:io';

/// The resources folder of each language, relative to apps/mobile.
const _resources = 'android/app/src/main/res';

/// language -> values folder; the default `values` is Spanish.
const languages = {
  'es': 'values',
  'en': 'values-en',
  'it': 'values-it',
  'pt': 'values-pt',
};

/// The strings the iOS notices read (ios/Runner/Notices/NoticePoster.swift).
const keys = [
  'notice_due_one',
  'notice_due_many',
  'notice_and',
  'notice_and_i',
  'notice_guest',
];

final _entry = RegExp(
  r'<string\s+name="([^"]+)"[^>]*>(.*?)</string>',
  dotAll: true,
);

/// The Android resource text [raw] as plain text.
String unescapeAndroid(String raw) {
  var text = raw.trim();
  // A value in double quotes keeps its spaces; the quotes are not part of it.
  if (text.length >= 2 && text.startsWith('"') && text.endsWith('"')) {
    text = text.substring(1, text.length - 1);
  }
  text = text
      .replaceAll('&lt;', '<')
      .replaceAll('&gt;', '>')
      .replaceAll('&quot;', '"')
      .replaceAll('&apos;', "'")
      .replaceAll('&amp;', '&');
  final out = StringBuffer();
  for (var i = 0; i < text.length; i++) {
    final c = text[i];
    if (c != r'\' || i + 1 == text.length) {
      out.write(c);
      continue;
    }
    final next = text[++i];
    out.write(switch (next) {
      'n' => '\n',
      't' => '\t',
      _ => next,
    });
  }
  return out.toString();
}

/// [text] as the inside of a `.strings` double-quoted value.
String escapeStrings(String text) {
  final withFormat = text.replaceAllMapped(
    RegExp(r'%(\d+\$)?s'),
    (_) => '%@',
  );
  return withFormat
      .replaceAll(r'\', r'\\')
      .replaceAll('"', r'\"')
      .replaceAll('\n', r'\n')
      .replaceAll('\t', r'\t');
}

/// The `Notices.strings` text for the strings.xml text [xml].
String notices(String xml, String source) {
  final found = {
    for (final m in _entry.allMatches(xml)) m.group(1)!: m.group(2)!,
  };
  final out = StringBuffer()
    ..writeln('/* Generated by scripts/gen-ios-strings.dart from $source. */')
    ..writeln(
      '/* Do not edit: run `dart run scripts/gen-ios-strings.dart` in apps/mobile and commit the result. */',
    );
  for (final key in keys) {
    final raw = found[key];
    if (raw == null) throw StateError('$source has no string "$key"');
    out.writeln('"$key" = "${escapeStrings(unescapeAndroid(raw))}";');
  }
  return out.toString();
}

void main() {
  languages.forEach((language, folder) {
    final source = '$_resources/$folder/strings.xml';
    final text = notices(File(source).readAsStringSync(), source);
    final dir = Directory('ios/Runner/$language.lproj')
      ..createSync(recursive: true);
    File('${dir.path}/Notices.strings').writeAsStringSync(text);
    print('wrote ${dir.path}/Notices.strings');
  });
}
